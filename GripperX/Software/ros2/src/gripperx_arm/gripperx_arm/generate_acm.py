"""Generate config/arm_allowed_collisions.yaml from the robot description.

The allowed-collision list is NOT hand-written. A link pair is allowed when
  * adjacent (scope "always"): joined by a joint, skipping geometry-less frames
    such as arm_base_link, so their primitives may overlap by construction;
  * its primitives overlap anywhere in the HOME NEIGHBOURHOOD (scope
    "home_neighbourhood"): arm joints at home +- home_pose_tolerance_rad, the
    gripper over its whole open..close travel (both signs, since the sign is
    unverified) +- the same tolerance; the steering over its full URDF range.
    Each such pair says at which tolerance it first appears and how close the
    MESHES come there (vertex-based): a clearance > 0 means the overlap is an
    artefact of the boxes, not contact.

TO-VERIFY, inherited: home = arm_calibration.yaml zero_ticks (one source,
gripperx_arm.poses) - so home is q = 0 by construction, and the tolerance stands
in for the unknown calibration error.

OVER-PERMISSION, deliberately left to the filter: a pair allowed here is
allowed for the PAIR, not for a pose. Only "always" pairs are safe to ignore
everywhere; "home_neighbourhood" pairs should be ignored only while the arm is
inside that neighbourhood.

The file also records, per arm link, how its boxes enclose its visual mesh.

    python3 -m gripperx_arm.generate_acm            # rewrite the file
    python3 -m gripperx_arm.generate_acm --check    # exit 1 if it is stale
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

import numpy as np
import yaml

from gripperx_arm.kinematics import ArmKinematics, TickCalibration, boxes_overlap

PKG = Path(__file__).resolve().parents[1]
BANNER = ('# GENERATED by `python3 -m gripperx_arm.generate_acm` from the robot description,\n'
          '# arm_poses.yaml and arm_calibration.yaml. DO NOT EDIT; regenerate.\n')


_OVERRIDE = {}


def description_dir() -> Path:
    if 'desc' in _OVERRIDE:
        return _OVERRIDE['desc']
    src = PKG.parent / 'gripperx_description'
    if (src / 'urdf').is_dir():
        return src
    from ament_index_python.packages import get_package_share_directory
    return Path(get_package_share_directory('gripperx_description'))


def config_dir() -> Path:
    if 'cfg' in _OVERRIDE:
        return _OVERRIDE['cfg']
    if (PKG / 'config').is_dir():
        return PKG / 'config'
    from ament_index_python.packages import get_package_share_directory
    return Path(get_package_share_directory('gripperx_arm')) / 'config'


def load_urdf(name: str = 'gripperx_v1.urdf.xacro') -> str:
    import xacro
    return xacro.process_file(str(description_dir() / 'urdf' / name)).toxml()


def read_stl(path: Path) -> np.ndarray:
    d = path.read_bytes()
    n = struct.unpack('<I', d[80:84])[0]
    raw = np.frombuffer(d[84:84 + n * 50], dtype=np.uint8).reshape(n, 50)
    return raw[:, 12:48].copy().view('<f4').reshape(n, 3, 3).astype(float)


def _fixed(cfg: Path):
    from gripperx_arm.poses import calibration_from_doc, resolve
    poses = yaml.safe_load((cfg / 'arm_poses.yaml').read_text())['arm_action_server'][
        'ros__parameters']
    return resolve(poses, calibration_from_doc(
        yaml.safe_load((cfg / 'arm_calibration.yaml').read_text())))


def home_q(kin: ArmKinematics, cfg: Path):
    cal = yaml.safe_load((cfg / 'arm_calibration.yaml').read_text())
    home = _fixed(cfg)['home']
    c = cal['arm_joint_state_relay']['ros__parameters']
    q = TickCalibration(c['urdf_joints'], c['zero_ticks'], c['signs'], c['ticks_per_rev'],
                        c.get('range_center_rad')).to_radians(home)
    assert list(q) == kin.joint_names, 'calibration joints differ from the URDF'
    return q


def _surface_samples(tris: np.ndarray, n: int, rng) -> np.ndarray:
    a = np.linalg.norm(np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0]), axis=1)
    i = rng.choice(len(tris), n, p=a / a.sum())
    u, v = rng.random((2, n))
    m = u + v > 1
    u[m], v[m] = 1 - u[m], 1 - v[m]
    t = tris[i]
    return t[:, 0] + u[:, None] * (t[:, 1] - t[:, 0]) + v[:, None] * (t[:, 2] - t[:, 0])


def _box_surface(h: np.ndarray, step: float) -> np.ndarray:
    pts = []
    for ax in range(3):
        o = [k for k in range(3) if k != ax]
        g0 = np.linspace(-h[o[0]], h[o[0]], max(2, int(2 * h[o[0]] / step) + 1))
        g1 = np.linspace(-h[o[1]], h[o[1]], max(2, int(2 * h[o[1]] / step) + 1))
        a, b = np.meshgrid(g0, g1)
        for sgn in (-1, 1):
            p = np.zeros((a.size, 3))
            p[:, o[0]], p[:, o[1]], p[:, ax] = a.ravel(), b.ravel(), sgn * h[ax]
            pts.append(p)
    return np.vstack(pts)


def padding_report(kin: ArmKinematics, urdf_xml: str) -> dict:
    """Per arm link, in mm: the smallest clearance between the mesh and the outer
    surface of its boxes (the padding where it is tightest), and the largest
    distance from any point of that outer surface to the mesh (where the boxes
    are loosest). Sampled at 2 mm on the boxes and ~30k points on the mesh."""
    import xml.etree.ElementTree as ET
    rng = np.random.default_rng(0)
    out = {}
    frames0 = kin.fk()
    prims = {}
    for p in kin.collision_primitives(frames=frames0):
        prims.setdefault(p.link, []).append(p)
    for link in ET.fromstring(urdf_xml).findall('link'):
        name = link.get('name')
        if name not in prims or link.find('visual') is None:
            continue
        fn = link.find('visual/geometry/mesh').get('filename').split('/')[-1]
        tris = read_stl(description_dir() / 'meshes' / fn)          # link frame
        boxes = []
        for p in prims[name]:
            t = np.linalg.inv(frames0[name]) @ p.frame               # box in link frame
            boxes.append((t, np.linalg.inv(t), np.array(p.size) / 2))
        mesh_pts = np.vstack([_surface_samples(tris, 30000, rng), tris.reshape(-1, 3)])

        def local(b, pts):
            return pts @ b[1][:3, :3].T + b[1][:3, 3]

        clear = np.full(len(mesh_pts), -np.inf)
        for b in boxes:
            lp = local(b, mesh_pts)
            c = (b[2] - np.abs(lp)).min(1)
            clear = np.maximum(clear, c)
        outer = []
        for b in boxes:
            sp = _box_surface(b[2], 0.002)
            w = sp @ b[0][:3, :3].T + b[0][:3, 3]
            inside_other = np.zeros(len(w), bool)
            for o in boxes:
                if o is not b:
                    inside_other |= np.all(np.abs(local(o, w)) < o[2] - 1e-9, axis=1)
            outer.append(w[~inside_other])
        outer = np.vstack(outer)
        m2 = (mesh_pts ** 2).sum(1)
        gap = 0.0
        for chunk in np.array_split(outer, max(1, len(outer) // 256)):
            d2 = (chunk ** 2).sum(1)[:, None] - 2 * chunk @ mesh_pts.T + m2[None, :]
            gap = max(gap, float(np.sqrt(max(d2.min(1).max(), 0.0))))
        out[name] = {'boxes': len(boxes),
                     'min_clearance_mm': round(float(clear.min()) * 1e3, 1),
                     'max_gap_mm': round(gap * 1e3, 1)}
    return out


def neighbourhood(kin: ArmKinematics, cfg: Path):
    """(home q, tolerance, per-joint [lo, hi]) of the home neighbourhood."""
    fixed = _fixed(cfg)
    c = yaml.safe_load((cfg / 'arm_calibration.yaml').read_text())['arm_joint_state_relay'][
        'ros__parameters']
    tol = float(c['home_pose_tolerance_rad'])
    home = home_q(kin, cfg)
    rng = {n: [v - tol, v + tol] for n, v in home.items()}
    g = kin.joint_names[-1]
    gi = len(kin.joint_names) - 1
    travel = []
    for sign in (1, -1):        # gripper sign is unverified: cover both
        signs = list(c['signs'])
        signs[gi] = sign
        cal = TickCalibration(c['urdf_joints'], c['zero_ticks'], signs, c['ticks_per_rev'],
                              c.get('range_center_rad'))
        for key in ('open', 'close'):
            ticks = list(fixed['home'])
            ticks[gi] = fixed[key]
            travel.append(cal.to_radians(ticks)[g])
    rng[g] = [min(travel + [home[g]]) - tol, max(travel + [home[g]]) + tol]
    return home, tol, rng


def sample_poses(kin, home, rng_, tol_scale=1.0, n_random=600, seed=0):
    """Corners, per-joint extremes and random points of the neighbourhood box,
    shrunk towards home by tol_scale for the arm joints (not the gripper)."""
    names = kin.joint_names
    g = names[-1]
    lo = np.array([home[n] + (rng_[n][0] - home[n]) * (1.0 if n == g else tol_scale)
                   for n in names])
    hi = np.array([home[n] + (rng_[n][1] - home[n]) * (1.0 if n == g else tol_scale)
                   for n in names])
    mid = np.array([home[n] for n in names])
    out = [mid]
    for bits in range(2 ** len(names)):
        out.append(np.where([(bits >> i) & 1 for i in range(len(names))], hi, lo))
    for i in range(len(names)):
        for v in (lo[i], hi[i]):
            q = mid.copy()
            q[i] = v
            out.append(q)
    r = np.random.default_rng(seed)
    out += list(lo + r.random((n_random, len(names))) * (hi - lo))
    return out


def overlapping_pairs(kin, q, groups, skip=frozenset()):
    """Link pairs whose primitives overlap in pose q; body groups are tested
    against their bound box first."""
    arm = kin.collision_primitives(q)
    found = set()
    for i, a in enumerate(arm):
        cand = list(arm[i + 1:])
        for grp in groups:
            if grp.bound is None or boxes_overlap(a, grp.bound):
                cand += grp.samples
        for b in cand:
            key = tuple(sorted((a.link, b.link)))
            if a.link != b.link and key not in skip and key not in found \
                    and boxes_overlap(a, b):
                found.add(key)
    return found


def adjacent_pairs(kin):
    geo = {p.link for p in kin.collision_primitives()} | {p.link for p in kin.environment}

    def geo_parent(link):
        link = kin.parent_link.get(link)
        while link is not None and link not in geo:
            link = kin.parent_link.get(link)
        return link

    out = set()
    for link in kin.links:
        if link in geo and geo_parent(link) is not None:
            out.add(tuple(sorted((link, geo_parent(link)))))
    return out


def _mesh_clearance(kin, urdf_xml, pair, poses):
    """Smallest vertex-to-vertex distance between the two links' meshes over
    the given poses, in metres; None when a link has no mesh (body parts)."""
    import xml.etree.ElementTree as ET
    from scipy.spatial import cKDTree
    files = {}
    for link in ET.fromstring(urdf_xml).findall('link'):
        if link.get('name') in pair and link.find('visual/geometry/mesh') is not None \
                and link.get('name') in kin.links:
            fn = link.find('visual/geometry/mesh').get('filename').split('/')[-1]
            files[link.get('name')] = read_stl(description_dir() / 'meshes' / fn).reshape(-1, 3)
    if len(files) != 2:
        return None
    a, b = pair
    best = np.inf
    for q in poses:
        f = kin.fk(dict(zip(kin.joint_names, q)))
        pa = files[a] @ f[a][:3, :3].T + f[a][:3, 3]
        pb = files[b] @ f[b][:3, :3].T + f[b][:3, 3]
        best = min(best, float(cKDTree(pa).query(pb)[0].min()))
    return best


# Pairs the USER declared physically impossible to collide (scope "always": never
# checked, in every mode - pose, setpoints, recovery, planner, leader). Hand-kept here
# and rendered into the generated file, so regenerating keeps them.
USER_ALLOWED = [
    {'links': ['arm_limb1_link', 'lidar_link'],
     'reason': 'user_decision_2026-10-12',
     'scope': 'always',
     # User, 2026-10-12: the arm cannot touch the lidar; the real lidar is smaller than
     # the model's - 35 mm high on a 40 x 40 mm footprint it never leaves, flush with
     # the lid at the front; a collision is physically impossible in every case.
     'user_stated_lidar_mm': {'height': 35, 'footprint': [40, 40]},
     # Only this pair: every other arm link vs lidar_link stays checked.
     # 2026-10-13: the collision model now IS that envelope (geometry.yaml
     # lidar_envelope_*); lifting the exclusion stays the user's decision.
     'to_verify': 'lidar collision model corrected to the user-measured envelope '
                  '2026-10-13 (geometry.yaml lidar_envelope_*); whether this pair is '
                  'checked again is pending a user decision'},
]


def allowed_pairs(kin: ArmKinematics, urdf_xml: str, cfg: Path):
    home, tol, rng_ = neighbourhood(kin, cfg)
    env = kin.swept_environment()
    adj = adjacent_pairs(kin)
    seen, hits = {}, {}
    scales = np.linspace(0.0, 1.0, 11)
    for sc in scales:
        for q in sample_poses(kin, home, rng_, sc, n_random=150 if sc < 1 else 600):
            for pair in overlapping_pairs(kin, dict(zip(kin.joint_names, q)), env, adj):
                seen.setdefault(pair, float(sc * tol))
                if len(hits.setdefault(pair, [])) < 6:
                    hits[pair].append(q)
    exact = {p for p, t in seen.items() if t == 0.0}
    later = [t for p, t in seen.items() if p not in exact]
    pairs = [{'links': list(p), 'reason': 'adjacent', 'scope': 'always'} for p in sorted(adj)]
    pairs += [dict(p, links=sorted(p['links'])) for p in USER_ALLOWED]
    for p in sorted(seen):
        clear = _mesh_clearance(kin, urdf_xml, p, hits[p])
        entry = {'links': list(p), 'reason': 'overlap_near_home', 'scope': 'home_neighbourhood',
                 'first_seen_tolerance_deg': round(float(np.degrees(seen[p])), 1)}
        if clear is not None:
            entry['min_mesh_clearance_mm'] = round(clear * 1e3, 1)
            if clear > 1e-3:
                entry['reason'] = 'box_artefact_near_home'
        pairs.append(entry)
    nb = {'status': 'TO-VERIFY',
          'home_q_rad': {k: round(v, 6) for k, v in home.items()},
          'tolerance_rad': tol,
          'joint_range_rad': {k: [round(v[0], 6), round(v[1], 6)] for k, v in rng_.items()},
          # largest tested arm tolerance at which no pair beyond the exact-home
          # set appears (tested in steps of tolerance / 10)
          'exact_home_set_holds_up_to_deg':
              round(float(np.degrees((min(later) if later else tol + tol / 10) - tol / 10)), 1)}
    return nb, pairs


def render(desc: Path = None, cfg: Path = None) -> str:
    _OVERRIDE.clear()
    if desc is not None:
        _OVERRIDE['desc'] = desc
    if cfg is not None:
        _OVERRIDE['cfg'] = cfg
    urdf = load_urdf()
    kin = ArmKinematics(urdf)
    nb, pairs = allowed_pairs(kin, urdf, config_dir())
    doc = {'neighbourhood': nb, 'allowed_pairs': pairs, 'padding': padding_report(kin, urdf)}
    return BANNER + yaml.safe_dump(doc, sort_keys=False, default_flow_style=None, width=100)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args(argv)
    target = PKG / 'config' / 'arm_allowed_collisions.yaml'
    text = render()
    if args.check:
        ok = target.is_file() and target.read_text() == text
        print('current' if ok else f'STALE: regenerate {target}')
        return 0 if ok else 1
    target.write_text(text)
    print(f'wrote {target}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
