"""Generate config/arm_stop_protected.yaml: which arm self-pairs the MECHANICAL STOPS
already keep apart (user decision 2026-10-07).

A non-adjacent pair of arm links is `stop_protected` - never checked at runtime -
iff, over the joints BETWEEN the two links (the only ones that move them against
each other) inside the mechanical stops (gripperx_geometry ARM_JOINT_STOP_LOWER /
UPPER, recorded on the follower arm 2026-10-08), the exact distance between the two MESHES never
drops to 0 (no touching, no penetration, neither mesh inside the other):
  1. a search over a grid (<= 2 joints: 3 deg; 3 joints: 6 deg; more: 30000 random
     samples) for the closest poses by vertex distance, each re-checked exactly;
     any penetration there settles the pair as `checked`, with a witness pose;
  2. otherwise a branch-and-bound certificate (gripperx_arm.mesh_distance.certify)
     down to a floor half-width; evaluation budget exceeded -> `checked`.
Everything else stays checked. RESIDUAL ASSUMPTIONS, recorded in the file: the
stop angles are only as good as the follower calibration (calibration_verified
still false), the CAD meshes are the real parts, and features thinner than the
motion inside a floor box are not resolved.

    python3 -m gripperx_arm.stop_protected            # rewrite the file (minutes)
    python3 -m gripperx_arm.stop_protected --check    # exit 1 if its inputs changed
"""
from __future__ import annotations

import argparse
import hashlib
import math
import sys
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

import numpy as np
import yaml

from gripperx_arm.kinematics import ArmKinematics
from gripperx_arm.mesh_distance import MeshPair, certify, read_stl_triangles

BANNER = ('# GENERATED by `python3 -m gripperx_arm.stop_protected`. DO NOT EDIT; regenerate.\n'
          '# Arm self-pairs the mechanical stops keep apart (user decision 2026-10-07).\n')
FLOOR_RAD = math.radians(0.1)
BUDGET = 4000
TIME_LIMIT_S = 300.0      # per pair; an unsettled pair stays checked
RESIDUAL = ('stop angles depend on the follower calibration of 2026-10-08 (recorded on '
            'the follower; calibration_verified still false); CAD meshes == real parts; a '
            'feature thinner than the motion inside a floor box (floor_deg) is not resolved')


def _stops():
    from gripperx_geometry import constants as C
    return list(C.ARM_JOINT_STOP_LOWER), list(C.ARM_JOINT_STOP_UPPER)


def mesh_files(urdf_xml: str, kin: ArmKinematics, resolve) -> Dict[str, Path]:
    import xml.etree.ElementTree as ET
    out = {}
    for link in ET.fromstring(urdf_xml).findall('link'):
        mesh = link.find('visual/geometry/mesh')
        if link.get('name') in kin.links and mesh is not None:
            out[link.get('name')] = Path(resolve(mesh.get('filename')))
    return out


def chain(kin: ArmKinematics, a: str, b: str) -> List[str]:
    """Actuated joints between link a and its descendant b (a above b)."""
    js, cur = [], b
    while cur != a:
        j = kin._by_child.get(cur)
        if j is None:
            raise ValueError(f'{a} is not above {b}')
        if j.name in kin.limits:
            js.insert(0, j.name)
        cur = j.parent
    return js


def radii(kin: ArmKinematics, joints: Sequence[str], b: str, verts_b: np.ndarray) -> List[float]:
    """Per joint, a configuration-independent bound on the distance of b's mesh from
    the joint's axis (triangle inequality down the chain)."""
    reach = float(np.linalg.norm(verts_b, axis=1).max())
    out, acc, cur = {}, reach, b
    while True:
        j = kin._by_child[cur]
        if j.name in joints:
            out[j.name] = acc
        acc += float(np.linalg.norm(j.origin[:3, 3]))
        cur = j.parent
        if all(n in out for n in joints):
            break
    return [out[n] for n in joints]


def fingerprint(urdf_xml: str, kin: ArmKinematics, files: Dict[str, Path], lo, hi) -> str:
    h = hashlib.sha256()
    for link in sorted(files):
        h.update(link.encode())
        h.update(files[link].read_bytes())
    for j in kin._order:
        h.update(j.name.encode())
        h.update(np.round(j.origin, 9).tobytes())
        h.update(np.round(j.axis, 9).tobytes())
    h.update(np.round(np.array(lo + hi, float), 9).tobytes())
    h.update(f'{FLOOR_RAD} {BUDGET}'.encode())
    return h.hexdigest()


def classify(kin, pair: MeshPair, a: str, b: str, joints, lo, hi, rad, seed=0) -> dict:
    idx = [kin.joint_names.index(n) for n in joints]
    lo_j = np.array([lo[i] for i in idx])
    hi_j = np.array([hi[i] for i in idx])

    def rel(v):
        q = dict(zip(joints, v))
        f = kin.fk(q)
        return np.linalg.inv(f[a]) @ f[b]
    # 1. search for the closest poses
    n = len(joints)
    if n <= 3:
        step = math.radians(3 if n <= 2 else 6)
        axes = [np.linspace(l, h, max(2, int(math.ceil((h - l) / step)) + 1))
                for l, h in zip(lo_j, hi_j)]
        grid = np.array(np.meshgrid(*axes, indexing='ij')).reshape(n, -1).T
    else:
        grid = lo_j + np.random.default_rng(seed).random((30000, n)) * (hi_j - lo_j)
    from scipy.spatial import cKDTree
    tree = cKDTree(pair.va0)
    dvv = np.array([tree.query(pair.vb0 @ rel(v)[:3, :3].T + rel(v)[:3, 3])[0].min()
                    for v in grid])
    best = np.argsort(dvv)[:30]
    min_d = math.inf
    for k in best:
        d = pair.distance(rel(grid[k]))
        min_d = min(min_d, d)
        if d <= 0.0 or pair.contained(rel(grid[k])):
            return {'category': 'checked', 'reason': 'meshes touch or penetrate inside the stops',
                    'witness_deg': [round(math.degrees(v), 2) for v in grid[k]],
                    'min_mesh_distance_mm': 0.0, 'search_poses': int(len(grid))}
    # 2. certificate
    cert = certify(rel, pair, lo_j, hi_j, rad, FLOOR_RAD, BUDGET, TIME_LIMIT_S)
    out = {'category': 'stop_protected' if cert.protected else 'checked',
           'reason': cert.reason,
           'min_mesh_distance_mm': round(min(min_d, cert.min_distance) * 1e3, 3),
           'search_poses': int(len(grid)), 'evaluations': cert.evaluations,
           'floor_deg': round(math.degrees(FLOOR_RAD), 3), 'floor_boxes': cert.floor_boxes}
    if cert.witness:
        out['witness_deg'] = [round(math.degrees(v), 2) for v in cert.witness]
    return out


def render(urdf_xml: str, resolve, lo=None, hi=None, only=None, log=print) -> str:
    kin = ArmKinematics(urdf_xml)
    if lo is None:
        lo, hi = _stops()
    files = mesh_files(urdf_xml, kin, resolve)
    links = [l for l in kin.links if l in files]
    pairs = []
    for i, a in enumerate(links):
        for b in links[i + 1:]:
            joints = chain(kin, a, b)
            if len(joints) < 2:
                continue                   # adjacent: allowed by the ACM already
            if only and (a, b) not in only:
                continue
            tris_a, tris_b = read_stl_triangles(files[a]), read_stl_triangles(files[b])
            mp = MeshPair(tris_a, tris_b)
            rad = radii(kin, joints, b, mp.vb)
            log(f'{a} / {b}: joints {joints}')
            res = classify(kin, mp, a, b, joints, lo, hi, rad)
            log(f'  -> {res["category"]}: {res["reason"]}')
            pairs.append({'links': [a, b], 'joints': joints,
                          'stops_deg': [[round(math.degrees(lo[kin.joint_names.index(j)]), 2),
                                         round(math.degrees(hi[kin.joint_names.index(j)]), 2)]
                                        for j in joints], **res})
    doc = {'inputs_sha256': fingerprint(urdf_xml, kin, files, list(lo), list(hi)),
           'stops_source': 'gripperx_geometry ARM_JOINT_STOP_LOWER/UPPER (follower, 2026-10-08)',
           'residual_assumptions': RESIDUAL,
           'pairs': pairs}
    return BANNER + yaml.safe_dump(doc, sort_keys=False, default_flow_style=None, width=100)


def main(argv=None) -> int:
    from gripperx_arm.generate_acm import PKG, description_dir, load_urdf
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args(argv)
    target = PKG / 'config' / 'arm_stop_protected.yaml'
    urdf = load_urdf()

    def resolve(uri):
        return str(description_dir() / 'meshes' / uri.split('/')[-1])
    if args.check:
        kin = ArmKinematics(urdf)
        lo, hi = _stops()
        want = fingerprint(urdf, kin, mesh_files(urdf, kin, resolve), lo, hi)
        have = yaml.safe_load(target.read_text()).get('inputs_sha256') if target.is_file() else None
        print('current' if want == have else f'STALE: regenerate {target}')
        return 0 if want == have else 1
    target.write_text(render(urdf, resolve))
    print(f'wrote {target}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
