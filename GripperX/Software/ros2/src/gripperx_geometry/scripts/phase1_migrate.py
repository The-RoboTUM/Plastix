def edit_teleop_setup(text: str) -> str:
    if "keyboard_teleop.yaml" in text:
        return text
    anchor = "['config/teleop_mux.yaml']"
    if anchor not in text:
        raise RuntimeError("cannot find the config data_files entry")
    return text.replace(anchor, "['config/teleop_mux.yaml', 'config/keyboard_teleop.yaml']", 1)


def edit_cpp_values(text: str, fixes: list) -> str:
    for pattern, replacement in fixes:
        text, count = re.subn(pattern, replacement, text)
        if not count:
            raise RuntimeError(f"pattern not found: {pattern}")
    return text


def edit_list_default(text: str, name: str) -> str:
    """Drop a list-valued default, same reasoning as the scalar ones."""
    pattern = re.compile(
        rf"(declare_parameter\(\s*(['\"]){re.escape(name)}\2\s*,\s*)\[.*?\](\s*,?\s*\))",
        re.S)
    if not pattern.search(text):
        raise RuntimeError(f"no list default for {name!r}")
    text = pattern.sub(r"\g<1>Parameter.Type.DOUBLE_ARRAY\g<3>", text)
    return _ensure_parameter_import(text)


def edit_registry(text: str) -> str:
    """Empty the divergence registry — the point of every other edit."""
    pattern = re.compile(r"KNOWN_DIVERGENCES: dict\[str, tuple\[float, str\]\] = \{.*?\n\}", re.S)
    if not pattern.search(text):
        raise RuntimeError("cannot find the KNOWN_DIVERGENCES block")
    return pattern.sub(REGISTRY_EMPTY, text)


def edit_package_dep(text: str) -> str:
    """Add the test dependency, tolerating the two manifest shapes in this tree.

    Most packages group their <test_depend> entries; gripperx_teleop has none at
    all and goes straight from <exec_depend> to <export>. Anchoring only on
    <test_depend> made the whole migration refuse to run because of one file,
    which is the right failure but the wrong cause.
    """
    if "gripperx_geometry" in text:
        return text
    entry = "  <test_depend>gripperx_geometry</test_depend>\n"
    for anchor in ("  <test_depend>", "  <export>"):
        if anchor in text:
            return text.replace(anchor, entry + anchor, 1)
    raise RuntimeError("no <test_depend> or <export> to anchor the dependency to")


