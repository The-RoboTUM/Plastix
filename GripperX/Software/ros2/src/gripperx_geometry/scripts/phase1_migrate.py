#!/usr/bin/env python3
"""Perform the Phase 1 edits mechanically, so the intervention is minutes long.

WHY A SCRIPT AND NOT JUST DOING IT
    Every Phase 1 edit lands in a file some other session may also be editing.
    The cost of the intervention is not the typing, it is the window during
    which this branch holds changes to shared files and can conflict. A script
    that is written, reviewed and dry-run in advance collapses that window to
    one command plus a test run.

    It also makes the change reviewable BEFORE it exists: --dry-run prints the
    exact diff, so the manifest is generated from the real edit rather than
    written by hand alongside it and drifting from it.

WHAT IT DOES
    1. Node defaults -> Parameter.Type.DOUBLE. A node that cannot find its
       parameter file then fails at startup instead of running on a stale
       literal. This is the change that has the most value and the least code.
    2. The tape pair a=0.180 / b=0.110 -> the CAD pair 0.1809 / 0.1087 in the
       three control configs, per the GQ-1 decision of 2026-08-21.
    3. Test files import gripperx_geometry.constants instead of carrying
       literals.
    4. package.xml gains the dependency where a test now imports it.

WHAT IT DELIBERATELY DOES NOT DO
    It does not rewrite the prose. The comment blocks in those YAMLs carry the
    measurement history and the OP-29 reasoning, which is the most valuable
    text in the repo and must not be regenerated by a regex. Every remaining
    prose mention of a superseded number is REPORTED instead, for a human pass.

USAGE
    python3 scripts/phase1_migrate.py --src-root <ws>/Software/ros2/src
    python3 scripts/phase1_migrate.py --src-root ... --apply
"""

