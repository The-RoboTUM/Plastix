def _ensure_parameter_import(text: str) -> str:
    if "from rclpy.parameter import Parameter" in text:
        return text
    anchor = "from rclpy.node import Node"
    if anchor not in text:
        raise RuntimeError("cannot place the Parameter import: no `from rclpy.node import Node`")
    return text.replace(anchor, anchor + "\nfrom rclpy.parameter import Parameter", 1)


def edit_node_defaults(text: str, names: list[str]) -> str:
    for name in names:
        pattern = re.compile(
            rf"(declare_parameter\(\s*(['\"]){re.escape(name)}\2\s*,\s*)"
            rf"[-+]?\d+(?:\.\d+)?"
        )
        text, count = pattern.subn(rf"\g<1>Parameter.Type.DOUBLE", text)
        if not count:
            raise RuntimeError(f"no numeric declare_parameter for {name!r}")
    return _ensure_parameter_import(text)


def edit_values(text: str, fixes: dict[str, tuple[str, str]]) -> str:
    for key, (old, new) in fixes.items():
        pattern = re.compile(rf"^(\s*){re.escape(key)}:\s*{re.escape(old)}\s*$", re.M)
        if not pattern.search(text):
            raise RuntimeError(f"{key}: expected value {old} not found")
        text = pattern.sub(rf"\g<1>{key}: {new}   # {POINTER}", text)
    return text


def edit_test_constants(text: str, names: tuple[str, ...]) -> str:
    first = None
    for name in names:
        pattern = re.compile(rf"^{name}\s*=\s*[-+]?\d+(?:\.\d+)?\s*$", re.M)
        match = pattern.search(text)
        if not match:
            raise RuntimeError(f"no module-level constant {name}")
        if first is None:
            first = match.start()
        text = pattern.sub("", text, count=1)
    lines = text[:first].rstrip("\n") + "\n" + TEST_IMPORT + "\n\n" + text[first:].lstrip("\n")
    return re.sub(r"\n{4,}", "\n\n\n", lines)


def edit_model_call(text: str) -> str:
    pattern = re.compile(
        r"FourWIS4WIDKinematicModel\(\s*a=[-+]?\d+(?:\.\d+)?\s*,\s*"
        r"b=[-+]?\d+(?:\.\d+)?\s*,\s*wheel_radius=[-+]?\d+(?:\.\d+)?\s*\)"
    )
    if not pattern.search(text):
        raise RuntimeError("no literal FourWIS4WIDKinematicModel(...) call")
    text = pattern.sub("FourWIS4WIDKinematicModel(a=A, b=B, wheel_radius=WHEEL_RADIUS)", text)
    anchor = "from gripperx_control.swerve_kinematic_model import FourWIS4WIDKinematicModel"
    line = [ln for ln in text.splitlines() if ln.startswith(anchor)]
    if not line:
        raise RuntimeError("cannot place the constants import")
    return text.replace(line[0], line[0] + "\n" + TEST_IMPORT.rstrip("\n"), 1)


def edit_short_names(text: str, mapping: dict[str, str]) -> str:
    first = None
    for local in mapping:
        pattern = re.compile(rf"^{local}\s*=\s*[-+]?\d+(?:\.\d+)?\s*$", re.M)
        match = pattern.search(text)
        if not match:
            raise RuntimeError(f"no module-level constant {local}")
        if first is None:
            first = match.start()
        text = pattern.sub("", text, count=1)
    canonical_of = {
        "A": "HALF_WHEELBASE_KINGPIN",
        "B": "HALF_TRACK_KINGPIN",
        "WHEEL_RADIUS": "WHEEL_RADIUS_EFFECTIVE",
    }
    # Sorted by the IMPORTED name, which is what ament_flake8's I101 checks —
    # sorting by the alias passes review and fails the linter.
    pairs = sorted(
        ((canonical_of[source], local) for local, source in mapping.items()),
        key=lambda pair: pair[0],
    )
    imports = "from gripperx_geometry.constants import (  # noqa: E402\n"
    for canonical, local in pairs:
        imports += f"    {canonical} as {local},\n"
    imports += ")\n"
    text = text[:first].rstrip("\n") + "\n" + imports + "\n\n" + text[first:].lstrip("\n")
    return re.sub(r"\n{4,}", "\n\n\n", text)


