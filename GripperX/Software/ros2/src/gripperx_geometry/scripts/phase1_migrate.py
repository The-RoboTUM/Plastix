def build_edits(root: Path) -> tuple[dict[Path, tuple[str, str]], list[str]]:
    edits: dict[Path, tuple[str, str]] = {}
    problems: list[str] = []

    def stage(relpath: str, fn):
        """Apply one edit, composing with any edit already staged for this file.

        Two edits touch check_teleop_manoeuvre_path.py — the model call and the
        harness parameter list. Reading from disk each time made the second
        silently discard the first, which the dry run caught by the harness
        referencing a name the discarded edit would have imported. Staged text
        is therefore chained, and the original is kept only for the diff.
        """
        path = root / relpath
        if not path.is_file():
            problems.append(f"{relpath}: file not found")
            return
        original, current = edits.get(path, (None, None))
        if original is None:
            original = current = path.read_text()
        try:
            after = fn(current)
        except RuntimeError as exc:
            problems.append(f"{relpath}: {exc}")
            return
        if original != after:
            edits[path] = (original, after)

    for relpath, names in NODE_DEFAULTS.items():
        stage(relpath, lambda t, n=names: edit_node_defaults(t, n))
    for relpath, fixes in VALUE_FIXES.items():
        stage(relpath, lambda t, f=fixes: edit_values(t, f))
    for relpath, names in TEST_CONSTANTS.items():
        stage(relpath, lambda t, n=names: edit_test_constants(t, n))
    for relpath in TEST_MODEL_CALL:
        stage(relpath, edit_model_call)
    for relpath, mapping in TEST_SHORT_NAMES.items():
        stage(relpath, lambda t, m=mapping: edit_short_names(t, m))
    for relpath in PACKAGE_DEPS:
        stage(relpath, edit_package_dep)
    for relpath, fixes in CPP_VALUE_FIXES.items():
        stage(relpath, lambda t, f=fixes: edit_cpp_values(t, f))
    for relpath, name in LIST_DEFAULTS.items():
        stage(relpath, lambda t, n=name: edit_list_default(t, n))
    stage(LAUNCH_FILE, edit_launch)
    stage(TEST_HARNESS, edit_test_harness)
    stage(TELEOP_SETUP, edit_teleop_setup)
    stage(REGISTRY_FILE, edit_registry)

    return edits, problems


def prose_residue(root: Path) -> list[str]:
    """Lines that will still name a superseded number after the edits."""
    out = []
    for relpath in list(VALUE_FIXES) + list(NODE_DEFAULTS):
        path = root / relpath
        if not path.is_file():
            continue
        for number, line in enumerate(path.read_text().splitlines(), 1):
            stripped = line.strip()
            if not (stripped.startswith("#") or stripped.startswith("//")):
                continue
            if any(value in line for value in SUPERSEDED):
                out.append(f"{relpath}:{number}: {stripped[:96]}")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--src-root", type=Path, required=True)
    parser.add_argument("--apply", action="store_true", help="write the edits (default: show them)")
    parser.add_argument("--quiet-prose", action="store_true", help="skip the prose-residue report")
    args = parser.parse_args(argv)

    edits, problems = build_edits(args.src_root)

    new_file = args.src_root / KEYBOARD_CONFIG
    creating = not new_file.exists()

    if problems:
        print("PROBLEMS — nothing was written:")
        for problem in problems:
            print(f"  {problem}")
        return 1

    for path, (before, after) in sorted(edits.items()):
        relpath = path.relative_to(args.src_root)
        if args.apply:
            path.write_text(after)
            print(f"patched {relpath}")
        else:
            print("".join(difflib.unified_diff(
                before.splitlines(keepends=True), after.splitlines(keepends=True),
                fromfile=f"a/{relpath}", tofile=f"b/{relpath}",
            )), end="")

    if creating:
        content = keyboard_config_content(args.src_root)
        if args.apply:
            new_file.parent.mkdir(parents=True, exist_ok=True)
            new_file.write_text(content)
            print(f"created {KEYBOARD_CONFIG}")
        else:
            print(f"--- /dev/null\n+++ b/{KEYBOARD_CONFIG}")
            print("".join(f"+{line}\n" for line in content.splitlines()), end="")

    print(f"\n{len(edits)} files {'patched' if args.apply else 'would change'}"
          f"{', 1 file created' if creating else ''}")

    if not args.quiet_prose:
        residue = prose_residue(args.src_root)
        print(f"\nPROSE STILL NAMING A SUPERSEDED NUMBER — needs a human pass, {len(residue)} lines:")
        for line in residue:
            print(f"  {line}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
